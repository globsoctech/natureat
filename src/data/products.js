export function getProduct(slug) {
  return products.find((p) => p.slug === slug);
}

export function filterProducts({ category, q, bio, horeca } = {}) {
  const query = (q || "").trim().toLowerCase();
  return products.filter((p) => {
    if (category && category !== "all") {
      if (category === "bio") {
        if (!p.bio) return false;
      } else if (p.category !== category && !(category === "horeca" && p.horeca)) {
        return false;
      }
    }
    if (bio && !p.bio) return false;
    if (horeca && !p.horeca) return false;
    if (!query) return true;
    return [p.name, p.brand, p.origin, p.description].join(" ").toLowerCase().includes(query);
  });
}
